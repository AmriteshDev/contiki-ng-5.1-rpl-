#!/bin/bash

# ==========================================
# 1. SETUP VARIABLES 
# ==========================================
COOJA_DIR="/home/amritesh/contiki-ng-5.1_rpl/tools/cooja"
CSC_DIR="/home/amritesh/contiki-ng-5.1_rpl/examples/coap/simulations"
BASE_LOG_DIR="/home/amritesh/contiki-ng-5.1_rpl/examples/coap/result/logs"
# Attacker directory ka path yahan add kiya hai
ATTACKER_DIR="/home/amritesh/contiki-ng-5.1_rpl/examples/coap/coap-example-attacker"

SCENARIOS=("normal" "cc_request" "zero_counter")
#SCENARIOS=("zero_counter" )
NODES=(20 40 60 80 100)
#NODES=(100)
TOTAL_RUNS=3

# ==========================================
# 2. PROGRESS CALCULATION SETUP
# ==========================================
NUM_SCENARIOS=${#SCENARIOS[@]}
NUM_NODES=${#NODES[@]}
TOTAL_SIMULATIONS=$((NUM_SCENARIOS * NUM_NODES * TOTAL_RUNS))
CURRENT_SIM=0

echo "STARTING MASS AUTOMATION"
echo "Total Simulations to run: $TOTAL_SIMULATIONS"
echo "========================================================"

# ==========================================
# 3. AUTOMATION LOOP
# ==========================================
for s in "${SCENARIOS[@]}"
do
  # --- AUTO-CHANGE ATTACK MODE ---
  if [ "$s" == "normal" ]; then
    MODE=0
  elif [ "$s" == "zero_counter" ]; then
    MODE=1
  elif [ "$s" == "cc_request" ]; then
    MODE=2
  fi

  echo "========================================================"
  echo "  SCENARIO: $s | Setting ATTACK_MODE: $MODE"
  echo "========================================================"
  
  # Attacker ki project-conf.h file update karna
  sed -i "s/#define ATTACK_MODE .*/#define ATTACK_MODE $MODE/" "$ATTACKER_DIR/project-conf.h"

  # Attacker folder mein jaakar purana build clean karna
  cd "$ATTACKER_DIR"
  make clean TARGET=cooja > /dev/null 2>&1
  
  for n in "${NODES[@]}"
  do
    mkdir -p "$BASE_LOG_DIR/$s/log$n"
    
    for r in $(seq 1 $TOTAL_RUNS)
    do
      CURRENT_SIM=$((CURRENT_SIM + 1))
      PERCENT=$((CURRENT_SIM * 100 / TOTAL_SIMULATIONS))
      
      SEED="${RANDOM}${RANDOM}"
      CSC_FILE="$CSC_DIR/$s/${s}_${n}.csc"
      LOG_FILE="$BASE_LOG_DIR/$s/log$n/log${n}_${r}.txt"
      
      echo ""
      echo "--------------------------------------------------------"
      echo "PROGRESS: [ $PERCENT% ] completed ($CURRENT_SIM out of $TOTAL_SIMULATIONS)"
      echo "RUNNING: Scenario: [$s] | Nodes: $n | Run: $r/$TOTAL_RUNS | Seed: $SEED"
      echo "--------------------------------------------------------"
      
      if [ ! -f "$CSC_FILE" ]; then
          echo "Error: $CSC_FILE nahi mili! Skipping..."
          continue
      fi

      # Cooja folder mein waapas jaana
      cd "$COOJA_DIR"
      
      # FIX: Purani testlog ko delete karein taaki purana data naye run mein mix na ho
      rm -f COOJA.testlog
      
      # Run Cooja and hide Gradle terminal output (--no-daemon add kiya h taki hang na ho)
      ./gradlew run --no-daemon --args="--no-gui --random-seed=$SEED $CSC_FILE" > console_output.txt
      
      # Move the actual log file generated by Cooja to your results folder
      if [ -f "COOJA.testlog" ]; then
          mv COOJA.testlog "$LOG_FILE"
          echo "✅ Saved Data to: $s/log$n/log${n}_${r}.txt"
      else
          echo "❌ Error: COOJA.testlog nahi mili!"
      fi
      
    done
  done
done

echo ""
echo "PROGRESS: [ 100% ] - ALL $TOTAL_SIMULATIONS SIMULATIONS COMPLETED SUCCESSFULLY!"
